num1 = input("Digite um número")
num2 = input("Digite outro número")
soma = float(num1) + float(num2)
print(f"A soma dos seus numeros será {soma}")
subtração = float(num1) - float(num2)
print(f"A subtração dos seus numeros será {subtração}")
multiplicação = float(num1) * float(num2)
print(f"A multiplicação dos seus numeros será {multiplicação}")
divisão = float(num1) / float(num2)
print(f"A divisão dos seus numeros será {divisão}")